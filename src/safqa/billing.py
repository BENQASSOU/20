"""Subscription plans, trial and licence keys.

Licence key format:  SAFQA-<PLAN>-<YYYYMMDD>-<CUSTOMER>-<SIG>
SIG = first 10 chars of base32(HMAC-SHA256(secret, "PLAN|YYYYMMDD|CUSTOMER")).

Keys are generated by the publisher with tools/make_license.py.  This
offline check is fine to launch with; once you have a payment provider
(CMI, virement, mobile money...) move the verification to a server, since
a secret shipped inside an APK can be extracted.
"""

